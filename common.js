/* スプレッドシート由来の文字列を HTML に埋め込む前に無害化する。

   各ページはテンプレート文字列を innerHTML に流し込んでいるため、
   タイトルや説明文に < や & が含まれると表示が崩れる。
   管理画面から入る値なので攻撃を想定したものではないが、
   チラシの「＜お知らせ＞」を半角で入力した程度で壊れるのを防ぐ。

   本文（body）はこの関数を通さない。お知らせ記事の本文には
   <a> タグを直接書いて外部リンクを張る運用にしているため。 */
function esc(v) {
  return String(v == null ? '' : v)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
